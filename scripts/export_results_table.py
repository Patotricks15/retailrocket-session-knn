"""Export the evaluation results as a LaTeX table and a Markdown table.

Having one generator feed both `paper/tables/results.tex` and the README block
is what stops the two surfaces from drifting apart as the model changes.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT / "src"))

from recommender.cli import _build_models, _load_split  # noqa: E402
from recommender.evaluation import evaluate  # noqa: E402

COLUMNS = ["model", "recall", "mrr", "coverage", "recall_cold", "n_cold"]
HEADERS = {
    "model": "Model",
    "recall": "Recall@20",
    "mrr": "MRR@20",
    "coverage": "Coverage",
    "recall_cold": "Recall@20 (cold)",
    "n_cold": "N cold",
}


def compute_results(events: Path, k: int, seed: int) -> pd.DataFrame:
    _, split = _load_split(events)
    rows = []
    for name, model in _build_models(seed).items():
        model.fit(split)
        rows.append(evaluate(model, split, k=k, partition="test", model_name=name).as_row())
    return pd.DataFrame(rows)[COLUMNS].sort_values("recall", ascending=False)


def to_latex(frame: pd.DataFrame, k: int) -> str:
    best = frame["recall"].max()
    lines = [
        "% Generated by scripts/export_results_table.py -- do not edit by hand.",
        r"\begin{table}[t]",
        r"  \centering",
        r"  \caption{Next-item-in-session ranking quality on the held-out test",
        r"  partition ($K=" + str(k) + r"$). Hyperparameters were selected on the",
        r"  validation partition; the test partition was read once. The",
        r"  ``cold'' columns restrict the metric to single-item prefixes.}",
        r"  \label{tab:results}",
        r"  \begin{tabular}{lrrrrr}",
        r"    \toprule",
        "    " + " & ".join(HEADERS[c] for c in COLUMNS) + r" \\",
        r"    \midrule",
    ]
    for _, row in frame.iterrows():
        cells = [str(row["model"]).replace("_", r"\_")]
        for col in COLUMNS[1:]:
            if col == "n_cold":
                cells.append(str(int(row[col])))
                continue
            value = f"{row[col]:.4f}"
            cells.append(rf"\textbf{{{value}}}" if col == "recall" and row[col] == best else value)
        lines.append("    " + " & ".join(cells) + r" \\")
    lines += [r"    \bottomrule", r"  \end{tabular}", r"\end{table}", ""]
    return "\n".join(lines)


def to_markdown(frame: pd.DataFrame) -> str:
    header = "| " + " | ".join(HEADERS[c] for c in COLUMNS) + " |"
    sep = "|" + "|".join(["---"] * len(COLUMNS)) + "|"
    rows = [
        "| "
        + " | ".join(
            [str(r["model"])]
            + [
                f"{r[c]:.4f}" if c != "n_cold" else str(int(r[c]))
                for c in COLUMNS[1:]
            ]
        )
        + " |"
        for _, r in frame.iterrows()
    ]
    return "\n".join([header, sep, *rows])


def main() -> int:
    import argparse

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--events", type=Path, default=PROJECT_ROOT / "data" / "events.csv")
    parser.add_argument("--k", type=int, default=20)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    if not args.events.exists():
        raise SystemExit(f"{args.events} not found. Run scripts/download_data.py --synthetic")

    frame = compute_results(args.events, args.k, args.seed)

    tables = PROJECT_ROOT / "paper" / "tables"
    tables.mkdir(parents=True, exist_ok=True)
    (tables / "results.tex").write_text(to_latex(frame, args.k))

    artifacts = PROJECT_ROOT / "artifacts"
    artifacts.mkdir(exist_ok=True)
    frame.to_csv(artifacts / "results.csv", index=False)
    (artifacts / "results.md").write_text(to_markdown(frame) + "\n")

    print(to_markdown(frame))
    print(f"\nwrote {tables / 'results.tex'}")
    print(f"wrote {artifacts / 'results.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
